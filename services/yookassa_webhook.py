async def yookassa_webhook_handler(request: web.Request) -> web.Response:
    """
    Handles incoming HTTP POST webhook notifications from YooKassa:
    - Event 'payment.succeeded'
    - Event 'payment.canceled'
    """
    bot: Bot = request.app["bot"]

    try:
        data = await request.json()
    except Exception as exc:
        logger.warning("Invalid JSON in YooKassa webhook request: %s", exc)
        return web.Response(status=400, text="Bad Request")

    event = data.get("event")
    obj = data.get("object", {})
    payment_id = obj.get("id")

    logger.info("Received YooKassa webhook: event=%s, payment_id=%s", event, payment_id)

    if not payment_id:
        return web.Response(status=200, text="OK")

    if event == "payment.succeeded":
        # Independently verify status with YooKassa API for bulletproof security
        try:
            verified = await yookassa_client.get_payment(payment_id)
            if verified.get("status") == "succeeded":
                await process_successful_payment(bot, payment_id)
            else:
                logger.warning(
                    "Webhook reported succeeded, but API returned %s for payment %s",
                    verified.get("status"),
                    payment_id,
                )
        except Exception as exc:
            logger.error("Failed to verify payment %s with YooKassa API: %s. Background poller will retry safely.", payment_id, exc)

    elif event == "payment.canceled":
        await process_canceled_payment(payment_id)

    return web.Response(status=200, text="OK")


async def check_expiring_promo_reminders(bot: Bot) -> None:
    """
    Finds discount activations where remaining time is <= 2 hours,
    reminds the user that the discount will expire soon, and marks reminder_sent = 1.
    """
    try:
        from aiogram.types import InlineKeyboardMarkup, InlineKeyboardButton
        pending = await db.get_pending_discount_reminders()
        for act in pending:
            act_id = act["id"]
            user_id = act["user_id"]
            ddata = act.get("discount_data") or {}
            dmode = ddata.get("discount_mode") or ddata.get("type", "fixed")

            active_code = act.get("code")
            if active_code:
                if dmode == "fixed" and ddata.get("percent"):
                    pct_str = f"промокод «{active_code}» (-{ddata.get('percent')}%)"
                else:
                    pct_str = f"промокод «{active_code}»"
            else:
                pct_str = "промокод на скидку"

            kb = InlineKeyboardMarkup(
                inline_keyboard=[
                    [
                        InlineKeyboardButton(
                            text="💳 Использовать скидку", callback_data="menu_topup"
                        ),
                    ],
                ]
            )

            text = (
                "⏰ <b>Ваша скидка скоро сгорит!</b>\n\n"
                f"Вы ранее активировали {pct_str}, но ещё не воспользовались им.\n"
                "До окончания действия скидки осталось <b>меньше 2 часов</b>!\n\n"
                "Успейте пополнить баланс по специальной цене, пока промокод активен:"
            )

            try:
                await bot.send_message(
                    chat_id=user_id,
                    text=text,
                    reply_markup=kb,
                    parse_mode="HTML",
                )
                logger.info("Sent expiring promo reminder to user %s (activation %s)", user_id, act_id)
            except Exception as send_err:
                logger.debug("Failed to send promo reminder to %s: %s", user_id, send_err)
            finally:
                await db.mark_discount_reminder_sent(act_id)

    except Exception as exc:
        logger.debug("Error in check_expiring_promo_reminders: %s", exc)


async def process_pending_audio_deliveries(bot: Bot) -> None:
    """
    Checks for tracks that were successfully generated by AI but could not be immediately
    uploaded to Telegram due to network timeouts / Telegram edge drops.
    Pulls from queue and delivers MP3s directly to users.
    """
    try:
        from aiogram.types import BufferedInputFile
        from aiogram.exceptions import TelegramForbiddenError, TelegramBadRequest
        from handlers.generation import generate_track_title
        from keyboards.inline import get_after_generation_keyboard
        import re
        import html
        import httpx

        pending_tracks = await db.get_pending_deliveries(limit=5)
        if not pending_tracks:
            return

        logger.info("Found %s pending audio deliveries. Processing...", len(pending_tracks))

        for item in pending_tracks:
            task_id = item["task_id"]
            user_id = item["user_id"]
            audio_url = item.get("audio_url")
            image_url = item.get("image_url")
            artist_name = item.get("artist")
            prompt = item.get("prompt")
            instrumental = bool(item.get("instrumental"))
            lyrics = item.get("lyrics")
            duration = item.get("duration")

            if not audio_url:
                await db.mark_generation_delivered(task_id)
                continue

            # Fetch audio bytes
            try:
                async with httpx.AsyncClient(timeout=60.0) as http_client:
                    audio_resp = await http_client.get(audio_url)
                    audio_resp.raise_for_status()
                    audio_bytes = audio_resp.content

                    thumb_bytes = None
                    if image_url:
                        try:
                            img_resp = await http_client.get(image_url)
                            if img_resp.status_code == 200:
                                thumb_bytes = img_resp.content
                        except Exception as img_err:
                            logger.warning("Failed to fetch thumbnail for pending track %s: %s", task_id, img_err)

                track_title = generate_track_title(
                    lyrics=lyrics,
                    prompt=prompt,
                    instrumental=instrumental,
                )
                performer_display = f"{artist_name} & Trivela" if artist_name else "Trivela"
                display_caption = (
                    f"🎶 <b>{html.escape(performer_display)} | {html.escape(track_title)}</b>\n\n"
                    "📦 <i>Ваш трек доставлен из очереди отправки. Приятного прослушивания!</i>"
                )

                safe_performer = re.sub(r'[\\/*?:"<>|]', "", performer_display).strip()
                safe_title = re.sub(r'[\\/*?:"<>|]', "", track_title).strip()
                file_name = f"{safe_performer} - {safe_title}.mp3" if safe_title else f"{safe_performer}.mp3"

                audio_file = BufferedInputFile(audio_bytes, filename=file_name)
                thumb_file = (
                    BufferedInputFile(thumb_bytes, filename="cover.webp")
                    if thumb_bytes
                    else None
                )

                await bot.send_audio(
                    chat_id=user_id,
                    audio=audio_file,
                    thumbnail=thumb_file,
                    title=track_title,
                    performer=performer_display,
                    duration=int(duration) if duration else None,
                    caption=display_caption,
                    reply_markup=get_after_generation_keyboard(),
                    parse_mode="HTML",
                    request_timeout=180,
                )

                await db.mark_generation_delivered(task_id)
                logger.info("Successfully delivered delayed audio for task %s to user %s", task_id, user_id)

            except TelegramForbiddenError:
                logger.warning("User %s blocked the bot. Marking task %s as delivery failed.", user_id, task_id)
                await db.mark_generation_delivery_failed(task_id, reason="User blocked bot")
            except TelegramBadRequest as br_err:
                if "chat not found" in str(br_err).lower():
                    logger.warning("Chat %s not found. Marking task %s as delivery failed.", user_id, task_id)
                    await db.mark_generation_delivery_failed(task_id, reason="Chat not found")
                else:
                    logger.warning("Telegram BadRequest for task %s: %s. Will retry.", task_id, br_err)
            except Exception as deliv_err:
                logger.warning(
                    "Background delivery attempt failed for task %s (user %s): %s. Will retry on next cycle.",
                    task_id,
                    user_id,
                    deliv_err,
                )

            # Throttle between deliveries to avoid hitting Telegram upload rate limits
            await asyncio.sleep(2.0)

    except Exception as exc:
        logger.debug("Error in process_pending_audio_deliveries: %s", exc)


async def process_pending_treblo_generations(bot: Bot) -> None:
    """
    Checks for in-flight Treblo generation tasks that timed out in the user interaction flow
    or were interrupted by bot restarts / network drops.
    - If Treblo reports SUCCESS: retrieves audio, updates DB, queues for delivery.
    - If Treblo reports FAILURE: updates DB, refunds generation credit to user, sends notification.
    - If still GENERATING / PROCESSING: leaves in queue.
    - If stale (> 2 hours): marks failed, refunds user credit, sends notification.
    """
    try:
        from keyboards.inline import get_main_menu_keyboard

        pending_tasks = await db.get_pending_treblo_generations(max_age_minutes=120, min_age_seconds=60)
        if pending_tasks:
            logger.info("Found %s pending Treblo generation tasks. Checking status...", len(pending_tasks))

            for task in pending_tasks:
                task_id = task["task_id"]
                user_id = task["user_id"]

                try:
                    status = await treblo_client.get_status(task_id)
                except Exception as st_err:
                    logger.debug("Error checking status for Treblo task %s: %s", task_id, st_err)
                    continue

                if status == "SUCCESS":
                    logger.info("Pending Treblo task %s completed! Fetching audio details...", task_id)
                    try:
                        gen_res = await treblo_client.get_generation(task_id)
                        audio_url = (
                            gen_res.get("audio_url")
                            or (gen_res.get("song_paths") and gen_res["song_paths"][0])
                            or (gen_res.get("audio_paths") and gen_res["audio_paths"][0])
                        )
                        image_url = (
                            gen_res.get("image_url")
                            or gen_res.get("image_path")
                            or gen_res.get("cover_url")
                            or (gen_res.get("image_paths") and gen_res["image_paths"][0])
                        )
                        duration = gen_res.get("duration")

                        if audio_url:
                            await db.update_generation_status(
                                task_id=task_id,
                                status="SUCCESS",
                                audio_url=audio_url,
                                duration=float(duration) if duration else None,
                                image_url=image_url,
                            )
                            await db.mark_generation_pending_delivery(task_id)
                            logger.info("Pending Treblo task %s updated to SUCCESS and marked for delivery.", task_id)
                    except Exception as fetch_err:
                        logger.warning("Error fetching completed Treblo generation %s: %s", task_id, fetch_err)

                elif status in ("FAILURE", "FAILED", "ERROR"):
                    logger.warning("Pending Treblo task %s failed on AI server.", task_id)
                    await db.update_generation_status(
                        task_id=task_id,
                        status="FAILURE",
                        error_message="Генерация музыки завершилась ошибкой на сервере нейросети.",
                    )
                    await db.refund_generation_credit(user_id)
                    try:
                        await bot.send_message(
                            chat_id=user_id,
                            text=(
                                "😔 <b>Не удалось создать трек</b>\n\n"
                                "Нейросеть не смогла завершить генерацию трека.\n"
                                "Потраченная попытка возвращена на ваш баланс. Попробуйте ещё раз с другими настройками или стилем."
                            ),
                            reply_markup=get_main_menu_keyboard(),
                            parse_mode="HTML",
                        )
                    except Exception as notify_err:
                        logger.debug("Failed to notify user %s of failed task %s: %s", user_id, task_id, notify_err)

                await asyncio.sleep(0.5)

        # Handle abandoned stale tasks older than 2 hours
        stale_tasks = await db.get_stale_treblo_generations(max_age_minutes=120)
        for task in stale_tasks:
            task_id = task["task_id"]
            user_id = task["user_id"]
            logger.warning("Treblo task %s exceeded 2-hour timeout. Marking failed and refunding.", task_id)
            await db.update_generation_status(
                task_id=task_id,
                status="FAILURE",
                error_message="Время ожидания генерации превысило 2 часа.",
            )
            await db.refund_generation_credit(user_id)
            try:
                await bot.send_message(
                    chat_id=user_id,
                    text=(
                        "⏱ <b>Время ожидания генерации трека истекло</b>\n\n"
                        "Сервер не успел завершить обработку трека за отведённое время.\n"
                        "Потраченная попытка возвращена на ваш баланс."
                    ),
                    reply_markup=get_main_menu_keyboard(),
                    parse_mode="HTML",
                )
            except Exception:
                pass
            await asyncio.sleep(0.5)

    except Exception as exc:
        logger.debug("Error in process_pending_treblo_generations: %s", exc)


async def background_payments_poller(bot: Bot) -> None:
    """
    Safety net background worker:
    1. Periodically checks pending payments in DB against YooKassa API.
    2. Periodically checks Treblo API balance and alerts admins if credits are low.
    """
    logger.info(
        "Background poller started (payments interval: %s sec, uptime interval: %s sec)",
        settings.background_poller_interval_sec,
        settings.uptime_check_interval_sec,
    )

    last_treblo_check = 0.0
    last_uptime_check = 0.0
    last_cleanup_check = 0.0

    while True:
        try:
            now = asyncio.get_event_loop().time()

            # Record health/uptime metrics for Bot and Treblo API (configurable interval, default 5 min)
            if now - last_uptime_check >= settings.uptime_check_interval_sec or last_uptime_check == 0.0:
                last_uptime_check = now
                try:
                    # 1. Record bot heartbeat
                    await db.record_uptime_check("bot", "UP", latency_ms=0.0)

                    # 2. Ping Treblo API and record latency
                    t_start = time.perf_counter()
                    bal_res = await treblo_client.get_account_balance()
                    t_latency = round((time.perf_counter() - t_start) * 1000, 1)

                    if isinstance(bal_res, dict) and "error" in bal_res and bal_res.get("status_code") != 200:
                        err_msg = str(bal_res.get("error"))
                        await db.record_uptime_check("treblo_api", "DOWN", latency_ms=t_latency, error_message=err_msg)
                    else:
                        await db.record_uptime_check("treblo_api", "UP", latency_ms=t_latency)
                except Exception as up_exc:
                    logger.debug("Uptime check error: %s", up_exc)
                    await db.record_uptime_check("treblo_api", "DOWN", latency_ms=0.0, error_message=str(up_exc))

            # Clean up old uptime logs older than 14 days (runs every 6 hours)
            if now - last_cleanup_check >= 21600 or last_cleanup_check == 0.0:
                last_cleanup_check = now
                try:
                    await db.cleanup_old_uptime_logs(days=14)
                except Exception:
                    pass

            # Check Treblo API balance every 10 minutes (or on startup)
            if now - last_treblo_check > 600 or last_treblo_check == 0.0:
                last_treblo_check = now
                try:
                    from services.admin_alerts import check_treblo_credits_and_alert
                    await check_treblo_credits_and_alert(bot)
                except Exception as e:
                    logger.debug("Treblo balance background check: %s", e)

            # Periodically mark abandoned pending payments older than 2 hours as canceled
            try:
                await db.cleanup_stale_payments(max_age_hours=2)
            except Exception as e:
                logger.debug("Cleanup stale payments error: %s", e)

            # Check expiring promo discount reminders (push 2 hours before expiration)
            try:
                await check_expiring_promo_reminders(bot)
            except Exception as e:
                logger.debug("Expiring promo reminders check: %s", e)

            # Monitor and recover in-flight Treblo generation tasks
            try:
                await process_pending_treblo_generations(bot)
            except Exception as e:
                logger.debug("Pending Treblo generations background worker error: %s", e)

            # Process delayed audio deliveries for tracks queued due to Telegram lag
            try:
                await process_pending_audio_deliveries(bot)
            except Exception as e:
                logger.debug("Pending audio deliveries background worker error: %s", e)

            # Check pending payments (YooKassa & CryptoBot)
            pending_payments = await db.get_pending_payments(limit=30)
            for p in pending_payments:
                pid = p["payment_id"]
                provider = p.get("provider") or "yookassa"

                if provider == "cryptobot" and cryptobot_client.is_configured:
                    try:
                        # Extract invoice_id from payment_id (e.g. cb_123456_940290714)
                        parts = pid.split("_")
                        invoice_id = int(parts[1]) if len(parts) >= 2 and parts[1].isdigit() else None
                        if invoice_id:
                            inv = await cryptobot_client.get_invoice(invoice_id)
                            if inv:
                                st = inv.get("status")
                                if st == "paid":
                                    logger.info("Background poller discovered successful CryptoBot payment %s", pid)
                                    await process_successful_payment(bot, pid)
                                elif st == "expired":
                                    logger.info("Background poller discovered expired CryptoBot payment %s", pid)
                                    await process_canceled_payment(pid)
                    except Exception as err:
                        logger.debug("CryptoBot background check error for %s: %s", pid, err)

                elif provider == "yookassa" and yookassa_client.is_configured:
                    try:
                        payment_info = await yookassa_client.get_payment(pid)
                        status = payment_info.get("status")

                        if status == "succeeded":
                            logger.info("Background poller discovered successful payment %s", pid)
                            await process_successful_payment(bot, pid)
                        elif status == "canceled":
                            logger.info("Background poller discovered canceled payment %s", pid)
                            await process_canceled_payment(pid)
                    except Exception as err:
                        err_str = str(err)
                        if "429" in err_str:
                            logger.warning(
                                "YooKassa rate limit (429) hit in background poller. Backing off for 60s..."
                            )
                            await asyncio.sleep(60)
                            break
                        logger.debug("Background poller check error for %s: %s", pid, err)

                # Pacing: avoid sending bursts of requests
                await asyncio.sleep(0.25)
        except Exception as exc:
            logger.error("Unexpected error in background payments poller: %s", exc)

        await asyncio.sleep(settings.background_poller_interval_sec)


